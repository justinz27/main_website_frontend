    <h1 class="text-5xl font-bold text-[#5b8ddb] mt-5">
        Grievance Resolution Policy and Procedure
    </h1>

    <div class="border-l-4 border-[#7862e2] bg-[#7862e2]/5 rounded-r-md p-5 my-2">
        <p class="text-lg leading-relaxed">
            To raise a formal grievance, please fill out the
            <a href={grievanceFormUrl} target="_blank" rel="noreferrer" class="text-[#7862e2] font-semibold hover:underline">CPMSoc Grievance Form</a>.
            Submissions are received by the Welfare Officer and handled confidentially in line with the policy below.
        </p>
    </div>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        1. Purpose
    </h2>

    <p class="text-lg leading-relaxed">
        CPMSoc encourages individuals to raise grievances where they arise in line with this policy and procedure. Most grievances should be raised directly with CPMSoc and handled internally. CPMSoc Executives should aim to deal with any complaints in a prompt, sensitive, impartial, confidential, and supportive manner to seek resolution and prevent future conflict.
    </p>
    <p class="text-lg leading-relaxed">
        All parties should co-operate constructively in resolving matters. Complainants are encouraged to use the formal procedure only where the matter has not been resolved through informal dialogue and/or it is not safe or appropriate for informal resolution.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        2. Scope
    </h2>

    <p class="text-lg leading-relaxed">
        These policies and procedures apply to current UNSW students, staff, and members of CPMSoc.
    </p>
    <p class="text-lg leading-relaxed">
        This document is designed to be a guide only and does not prescribe the actions required to handle every possible grievance. CPMSoc Executives are expected to use discretion in handling grievances, considering the circumstances, purpose, and principles of this policy.
    </p>

    <h3 class="text-[22px] font-medium text-[#5b8ddb]">
        Matters Excluded from This Procedure
    </h3>

    <p class="text-lg leading-relaxed">
        The following grievances should not be pursued under this procedure:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5">
        <li>Disputes relating to matters beyond the control of CPMSoc (e.g., behaviour of attendees at a nearby event).</li>
        <li>Personal disputes where none of the parties are acting on behalf of CPMSoc.</li>
        <li>
            Complaints relating to incidents that occurred more than three (3) months prior to being raised, unless a reasonable explanation for the delay is provided.
            <ul class="list-[circle] list-outside pl-5 ml-5">
                <li>For longer-term or repetitive issues, at least one instance must have occurred within this period.</li>
            </ul>
        </li>
    </ul>

    <p class="text-lg leading-relaxed mb-5">
        Grievances or complaints involving criminal offences should not be investigated by CPMSoc but reported directly to Arc.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        3. Definitions
    </h2>

    <ul class="list-none list-outside text-lg leading-relaxed mb-5 flex flex-col gap-3">
        <li><span class="font-semibold">Appeal:</span> A challenge or dispute of a decision made by CPMSoc in relation to a formal grievance.</li>
        <li><span class="font-semibold">Complaint:</span> An objection or criticism raised about any CPMSoc-related incident. A complaint may not require formal resolution but should always be acknowledged.</li>
        <li><span class="font-semibold">Complainant:</span> The individual who makes a complaint or raises a grievance.</li>
        <li><span class="font-semibold">Welfare Officer:</span> The CPMSoc Executive responsible for receiving and handling formal grievances (as specified in the CPMSoc Constitution). If unavailable or inappropriate, another Executive member will assume this role.</li>
        <li><span class="font-semibold">Grievance:</span> Any complaint, concern, dispute, or problem related to CPMSoc’s activities, events, or Executive behaviour that the complainant believes to be unfair or unjustified.</li>
        <li>
            <span class="font-semibold">Procedural Fairness:</span> The right to a fair process when decisions are made. This includes:
            <ul class="list-disc list-outside pl-5 ml-5">
                <li>The right to be heard and respond to allegations;</li>
                <li>Reasonable inquiry into matters in dispute;</li>
                <li>Proper documentation of grievances and investigations;</li>
                <li>A lack of bias during the process; and</li>
                <li>Decisions supported by evidence and reasons.</li>
            </ul>
        </li>
    </ul>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        4. Procedure Overview
    </h2>

    <p class="text-lg leading-relaxed mb-5">
        The following steps provide a guideline for handling grievances. CPMSoc Executives should adapt their response as appropriate to each situation.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        5. Informal Grievance Resolution
    </h2>

    <p class="text-lg leading-relaxed">
        Informal procedures are used for less serious or complex grievances with the aim of achieving a timely and reasonable resolution.
    </p>

    <h3 class="text-[22px] font-medium text-[#5b8ddb]">
        5.1 Self-Resolution
    </h3>

    <p class="text-lg leading-relaxed">
        If comfortable, the complainant should first attempt to resolve the grievance directly with the individual(s) involved. Self-resolution encourages constructive dialogue and helps prevent escalation.
    </p>
    <p class="text-lg leading-relaxed">
        However, self-resolution is not appropriate for serious grievances such as incidents of gendered violence or criminal behaviour. These should be reported immediately to one of the following:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5">
        <li>Arc via the Incident Reporting Form,</li>
        <li>UNSW via the Gendered Violence Reporting Portal or Student Complaints Portal, or</li>
        <li>The police (for serious indictable offences).</li>
    </ul>

    <h3 class="text-[22px] font-medium text-[#5b8ddb]">
        5.2 Other Informal Mechanisms
    </h3>

    <p class="text-lg leading-relaxed">
        Informal grievance resolution may include:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5 mb-5">
        <li>CPMSoc Executives facilitating informal discussions;</li>
        <li>Internal mediation between parties; or</li>
        <li>Raising awareness of appropriate behaviour within the Club.</li>
    </ul>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        6. Formal Grievance Resolution
    </h2>

    <p class="text-lg leading-relaxed">
        If informal resolution is unsuccessful, unsafe, or inappropriate, the complainant should raise the grievance with the Welfare Officer.
    </p>
    <p class="text-lg leading-relaxed">
        If the Welfare Officer is directly involved, or the complainant feels uncomfortable reporting to them, the grievance should be reported to another CPMSoc Executive.
    </p>

    <h3 class="text-[22px] font-medium text-[#5b8ddb]">
        6.1 Submitting a Formal Grievance
    </h3>

    <p class="text-lg leading-relaxed">
        Formal grievances can be submitted via the
        <a href={grievanceFormUrl} target="_blank" rel="noreferrer" class="text-[#7862e2] hover:underline">CPMSoc Grievance Form</a>.
        When submitting a grievance, the complainant must:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5">
        <li>Provide the grievance in writing;</li>
        <li>Include names, dates, and details of the incident(s);</li>
        <li>Attach supporting documentation (if applicable); and</li>
        <li>State the desired outcome.</li>
    </ul>

    <p class="text-lg leading-relaxed">
        If incomplete, the Welfare Officer will request a written report within five (5) days. The process will not advance until a formal report is received.
    </p>

    <h3 class="text-[22px] font-medium text-[#5b8ddb]">
        6.2 Initial Steps
    </h3>

    <p class="text-lg leading-relaxed">
        The Welfare Officer will follow up within five (5) working days (or as soon as practicable) to:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5">
        <li>Confirm the details and desired outcome;</li>
        <li>Explain this grievance policy; and</li>
        <li>Determine next steps or refer the grievance to another Executive if necessary.</li>
    </ul>

    <p class="text-lg leading-relaxed">
        If unsure how to proceed, the Welfare Officer should seek advice from Arc.
    </p>
    <p class="text-lg leading-relaxed mb-5">
        If inappropriate for CPMSoc to handle, the Welfare Officer must refer the grievance to Arc in writing.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        7. Investigation
    </h2>

    <p class="text-lg leading-relaxed">
        Where an investigation is required, the Welfare Officer may:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5">
        <li>Conduct interviews with relevant parties;</li>
        <li>Notify individuals of allegations and provide supporting evidence;</li>
        <li>Allow time for response; and</li>
        <li>Review all relevant evidence and documentation.</li>
    </ul>

    <p class="text-lg leading-relaxed">
        If a complainant does not consent to sharing their information with the respondent, the Welfare Officer cannot proceed and must dismiss the grievance to maintain procedural fairness.
    </p>
    <p class="text-lg leading-relaxed">
        Progress updates must be communicated throughout the process.
    </p>
    <p class="text-lg leading-relaxed mb-5">
        All decisions involving individuals must afford adequate notice, information, and opportunity to respond.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        8. Procedural Fairness
    </h2>

    <p class="text-lg leading-relaxed">
        All parties involved are entitled to:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5">
        <li>At least five (5) working days’ notice before any meeting;</li>
        <li>A reasonable and private location for meetings;</li>
        <li>Full information about allegations and evidence;</li>
        <li>Five (5) working days to prepare a response;</li>
        <li>The opportunity to respond;</li>
        <li>A fair inquiry into disputed matters; and</li>
        <li>The right to have a support person present.</li>
    </ul>

    <p class="text-lg leading-relaxed">
        Complainants will not participate in deciding outcomes.
    </p>
    <p class="text-lg leading-relaxed mb-5">
        The Welfare Officer acts as an impartial third party.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        9. Record Keeping
    </h2>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5 mb-5">
        <li>All conversations, actions, and dates must be documented and stored securely.</li>
        <li>Records may be shared with Arc, UNSW, or law enforcement if required.</li>
        <li>CPMSoc will maintain a confidential Welfare Officer email address for grievance-related communication.</li>
    </ul>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        10. Victimisation
    </h2>

    <p class="text-lg leading-relaxed">
        CPMSoc will report any instances of victimisation or retaliation against complainants to UNSW.
    </p>
    <p class="text-lg leading-relaxed mb-5">
        This includes individuals found to have made false or vexatious complaints or to have retaliated against others under this policy.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        11. Unreasonable Behaviour
    </h2>

    <p class="text-lg leading-relaxed">
        CPMSoc will not tolerate mistreatment of the Welfare Officer. Unreasonable behaviour includes:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5 mb-5">
        <li>Offensive or disrespectful conduct;</li>
        <li>Threats or coercion;</li>
        <li>Disruptive or obstructive behaviour during resolution;</li>
        <li>Harassment during or after the process; or</li>
        <li>Unreasonable demands.</li>
    </ul>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        12. Confidentiality and Discretion
    </h2>

    <p class="text-lg leading-relaxed">
        All parties must maintain confidentiality regarding identities and incidents involved in grievances.
    </p>
    <p class="text-lg leading-relaxed">
        If reporting to Arc, UNSW, or the police is required, the complainant will be informed and the report de-identified unless identification is required by law.
    </p>
    <p class="text-lg leading-relaxed mb-5">
        Any breach of confidentiality will be taken seriously and may lead to disciplinary action.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        13. Disciplinary Action
    </h2>

    <p class="text-lg leading-relaxed">
        After formal grievance procedures, disciplinary actions may include:
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5">
        <li>Formal warning;</li>
        <li>Ban from club events;</li>
        <li>Removal of membership; or</li>
        <li>Revocation of responsibilities or event management privileges.</li>
    </ul>

    <p class="text-lg leading-relaxed mb-5">
        Penalties must be proportionate, evidence-based, and communicated in writing.
    </p>

    <h2 class="text-3xl font-bold text-[#5b8ddb] mt-5">
        14. Appeal and Review of Decisions
    </h2>

    <h3 class="text-[22px] font-medium text-[#5b8ddb]">
        14.1 Internal Appeals Procedure
    </h3>

    <p class="text-lg leading-relaxed">
        If dissatisfied with how a grievance was handled, the complainant may appeal to the Club President (or another Executive if the President is involved).
    </p>
    <p class="text-lg leading-relaxed">
        Appeals must be submitted within five (5) working days of receiving the outcome and must specify the grounds for appeal (e.g., lack of procedural fairness).
    </p>
    <p class="text-lg leading-relaxed">
        The President will select two (2) other Executives (without conflicts of interest) to review the process and outcome. Their decision will be final within CPMSoc.
    </p>

    <h3 class="text-[22px] font-medium text-[#5b8ddb]">
        14.2 Appeals to Arc or UNSW
    </h3>

    <p class="text-lg leading-relaxed">
        In certain cases, grievances or appeals may be escalated to Arc or UNSW. Formal and informal CPMSoc procedures should be followed first.
    </p>

    <ul class="list-disc list-outside pl-5 text-lg leading-relaxed ml-5 mb-5">
        <li>Appeals to Arc must be in writing to <a href="mailto:advice@arc.unsw.edu.au" class="text-[#7862e2] hover:underline">advice@arc.unsw.edu.au</a>.</li>
    </ul>
